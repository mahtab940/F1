import assert from 'node:assert/strict';
import {resultSummary,loadCarResults} from './dist/car-details.js';
const result=(name,position,team='ferrari')=>({Driver:{givenName:name,familyName:'Driver'},position:String(position),Constructor:{constructorId:team}});
const summary=resultSummary([{Results:[result('First',1),result('Second',3),result('Other',2,'mclaren')]},{Results:[result('First',2),result('Substitute',10)]}],'ferrari');
assert.equal(summary.wins,1);
assert.equal(summary.podiums,3);
assert.equal(summary.starts,2);
assert.equal(summary.drivers.length,3);
assert.equal(summary.drivers[0].wins,1);
assert.equal(resultSummary([],'ferrari').wins,0);
let calls=0;
globalThis.fetch=async()=>({ok:true,json:async()=>({MRData:{total:'101',RaceTable:{Races:[{round:'1',raceName:'Test GP',Results:[result(calls++?'Second':'First',calls===1?1:3)]}]}}})});
const car={id:'2004-ferrari-f2004',year:2004};
const loaded=await loadCarResults(car);
assert.equal(calls,2);
assert.equal(loaded.starts,1,'Pages splitting a race are merged');
assert.equal(loaded.drivers.length,2);
await loadCarResults(car);
assert.equal(calls,2,'Repeated opens reuse results');
globalThis.fetch=async()=>({ok:false});
await assert.rejects(loadCarResults({...car,year:2005}));
console.log('PASS: car details totals, substitute drivers, pagination, caching and failure.');
